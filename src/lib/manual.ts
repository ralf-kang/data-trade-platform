export const MANUAL_GROUPS = Array.from(new Set(MANUAL_SECTIONS.map((s) => s.group)));

export function sectionsFor(audience: ManualAudience): ManualSection[] {
  return MANUAL_SECTIONS.filter((s) => s.audience.includes(audience));
}

/** 특정 화면에 해당하는 도움말 — 화면의 도움말 버튼이 어느 항목으로 갈지 결정한다. */
export function sectionsForRoute(pathname: string, audience: ManualAudience): ManualSection[] {
  return sectionsFor(audience).filter((s) => s.routes?.some((r) => pathname.startsWith(r)));
}

export function searchSections(query: string, audience: ManualAudience): ManualSection[] {
  const q = query.trim().toLowerCase();
  if (!q) return sectionsFor(audience);
  return sectionsFor(audience).filter((s) => {
    const haystack = [
      s.title,
      s.summary,
      ...s.body.map((b) => (b.type === 'ul' ? b.items.join(' ') : b.text)),
    ]
      .join(' ')
      .toLowerCase();
    return haystack.includes(q);
  });
}
